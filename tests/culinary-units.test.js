const assert = require('node:assert/strict');
const {convert} = require('../assets/culinary-units.js');
function near(actual, expected, eps = 1e-9) { assert.ok(Math.abs(actual - expected) < eps, `${actual} != ${expected}`); }
near(convert(1, 'lb', 'g'), 453.59237);
near(convert(1, 'oz', 'g'), 28.349523125);
near(convert(1, 'us_gallon', 'l'), 3.785411784);
near(convert(1, 'uk_gallon', 'l'), 4.54609);
near(convert(1, 'us_cup', 'ml'), 236.5882365);
near(convert(1, 'metric_cup', 'ml'), 250);
near(convert(1, 'us_tbsp', 'us_tsp'), 3);
near(convert(1, 'inch', 'cm'), 2.54);
near(convert(32, 'f', 'c'), 0);
near(convert(100, 'c', 'f'), 212);
near(convert(273.15, 'k', 'c'), 0);
near(convert(convert(17.35, 'us_fl_oz', 'ml'), 'ml', 'us_fl_oz'), 17.35);
assert.throws(() => convert(1, 'g', 'ml'), RangeError);
assert.throws(() => convert(1, 'pinch', 'tsp'), RangeError);
assert.throws(() => convert(Infinity, 'g', 'kg'), TypeError);
console.log('Culinary conversion tests passed');
const {convertText} = require('../assets/culinary-units.js');
assert.equal(convertText('1 lb', 'metric', false), '≈453.6 g');
assert.equal(convertText('1 U.S. gallon', 'metric', false), '≈3785 ml');
assert.equal(convertText('1 US gal', 'metric', false), '≈3785 ml');
assert.equal(convertText('۲–۳ قاشق غذاخوری', 'metric', true), '≈۲۹٫۵۷–۴۴٫۳۶ میلی‌لیتر');
assert.equal(convertText('نصف پیمانه', 'metric', true), '≈۱۱۸٫۳ میلی‌لیتر');
assert.equal(convertText('1 fl oz', 'metric', false), '≈29.57 ml');
assert.equal(convertText('1 oz', 'metric', false), '≈28.35 g');
assert.equal(convertText('100 g', 'imperial', false), '≈3.527 oz');
assert.equal(convertText('to taste', 'metric', false), 'to taste');
assert.equal(convertText('30–32%', 'imperial', false), '30–32%');
