#!/usr/bin/env python3
"""Build the offline ingredient search index from both recipe-page languages."""
from html.parser import HTMLParser
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parent.parent

class Ingredients(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.table_depth = 0
        self.in_tbody = False
        self.capture = False
        self.parts = []
        self.items = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'table':
            if self.table_depth:
                self.table_depth += 1
            elif 'ing' in attrs.get('class', '').split():
                self.table_depth = 1
        if not self.table_depth:
            return
        if tag == 'tbody':
            self.in_tbody = True
        if self.in_tbody and tag in ('th', 'td') and 'amt' not in attrs.get('class', '').split():
            self.capture = True
            self.parts = []

    def handle_data(self, data):
        if self.capture:
            self.parts.append(data)

    def handle_endtag(self, tag):
        if not self.table_depth:
            return
        if tag in ('th', 'td') and self.capture:
            text = ' '.join(' '.join(self.parts).split())
            if text:
                self.items.append(text)
            self.capture = False
        if tag == 'tbody':
            self.in_tbody = False
        if tag == 'table':
            self.table_depth -= 1

index = {}
for file in sorted((ROOT / 'recipes').glob('*.html')):
    if file.name.startswith('_'):
        continue
    terms = []
    for source in (file, ROOT / 'en' / 'recipes' / file.name):
        if not source.is_file():
            raise SystemExit(f'Missing bilingual recipe: {source}')
        parser = Ingredients()
        parser.feed(source.read_text(encoding='utf-8'))
        terms.extend(parser.items)
    index['recipes/' + file.name] = ' '.join(dict.fromkeys(terms))

output = '// Generated by tools/build-ingredient-index.py; do not edit manually.\n'
output += 'const INGREDIENT_SEARCH = ' + json.dumps(index, ensure_ascii=False, indent=2) + ';\n'
target = ROOT / 'assets' / 'ingredients.js'
if '--check' in sys.argv[1:]:
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        raise SystemExit('Ingredient index is out of date; run python3 tools/build-ingredient-index.py')
    print(f'Ingredient index current: {len(index)} bilingual recipe pages')
else:
    target.write_text(output, encoding='utf-8')
    print(f'Indexed {len(index)} bilingual recipe pages')
